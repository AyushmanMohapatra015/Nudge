import { test, expect } from '@playwright/test';
import { ownerAnalytics } from '../../lib/owner-analytics';
import { checksNow, invoiceChecksFixture } from '../fixtures/invoice-checks';

test('Invoice checks render exact independent warnings, remain unfiltered and refresh without API writes', async ({ page, request }) => {
  const before = await (await request.get('/api/workspace')).json();
  const workspace = invoiceChecksFixture(); let snapshot = ownerAnalytics(workspace, checksNow);
  let failed = false; const writes: string[] = [], errors: string[] = [];
  await page.route('**/api/analytics', route => route.fulfill({ status: failed ? 503 : 200, json: failed ? { error: 'fictional failure' } : { ...snapshot, stateSource: 'local-records' } }));
  page.on('request', r => { if (r.method() !== 'GET' && new URL(r.url()).pathname.startsWith('/api/')) writes.push(r.url()); });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/analytics');
  const checks = page.getByRole('region', { name: 'Invoice checks', exact: true });
  await expect(checks).toContainText('4 invoices need status review.', { timeout: 30000 });
  await expect(checks).toContainText('2 invoices have an unknown due date: $5.79 USD');
  await expect(checks).toContainText('unaffected by report filters');
  await expect(checks).toContainText('do not add their counts');
  await expect(checks.locator('time')).toHaveAttribute('datetime', checksNow.toISOString());
  await expect(checks.getByRole('link')).toHaveAttribute('href', '/');
  const text = await checks.innerText();
  const studio = page.getByRole('region', { name: 'AG Studio report builder' });
  const chart = studio.getByRole('figure', { name: 'chart, 1 series' });
  await chart.scrollIntoViewIfNeeded(); const box = await chart.boundingBox();
  await chart.click({ position: { x: box!.width * 0.5, y: box!.height * 0.65 } });
  await studio.getByRole('button', { name: 'Filters', exact: true }).click();
  await expect(studio.getByRole('button', { name: 'Cross Filters', exact: true })).toBeVisible();
  expect(await checks.innerText()).toBe(text);
  workspace.invoices = workspace.invoices.slice(-2); workspace.version++;
  snapshot = ownerAnalytics(workspace, checksNow);
  await page.getByRole('button', { name: 'Refresh local snapshot' }).click();
  await expect(checks).toContainText('No status or due-date issues are flagged');
  await expect(checks).toContainText('do not establish current PayPal status or reminder eligibility');
  failed = true; await page.getByRole('button', { name: 'Refresh local snapshot' }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Unable to load analytics. Try again shortly.' })).toBeVisible();
  await expect(checks).toHaveCount(0);
  failed = false; await page.getByRole('button', { name: 'Refresh local snapshot' }).click();
  await expect(checks).toContainText('Snapshot version 8');
  expect(writes).toEqual([]); expect(errors).toEqual([]);
  expect(await (await request.get('/api/workspace')).json()).toEqual(before);
});

test('Invoice checks menu, duplicate, delete, resize and refresh preserve session layout', async ({ page }) => {
  const snapshot = ownerAnalytics(invoiceChecksFixture(), checksNow);
  await page.route('**/api/analytics', route => route.fulfill({ json: { ...snapshot, stateSource: 'local-records' } }));
  await page.goto('/analytics');
  const studio = page.getByRole('region', { name: 'AG Studio report builder' });
  const checks = studio.getByRole('region', { name: 'Invoice checks', exact: true });
  await expect(checks).toHaveCount(1, { timeout: 30000 });
  await page.getByRole('button', { name: 'Edit report layout' }).click();
  await studio.getByRole('button', { name: 'Invoice checks', exact: true }).click();
  await expect(checks).toHaveCount(2);
  const added = studio.locator('.ag-studio-layout-widget').filter({ has: page.locator('.studio-invoice-checks') }).last();
  await added.hover(); await added.getByRole('button', { name: 'Duplicate widget', exact: true }).click();
  await expect(checks).toHaveCount(3);
  const duplicate = studio.locator('.ag-studio-layout-widget').filter({ has: page.locator('.studio-invoice-checks') }).last();
  await duplicate.hover(); await duplicate.getByRole('button', { name: 'Delete widget', exact: true }).click();
  await expect(checks).toHaveCount(2);
  const heightBefore = (await added.boundingBox())!.height;
  const handle = added.locator('.ag-studio-layout-widget-overlay-resize[data-direction="s"]');
  await handle.scrollIntoViewIfNeeded(); const box = await handle.boundingBox();
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2); await page.mouse.down();
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2 + 60, { steps: 8 }); await page.mouse.up();
  await expect.poll(async () => (await added.boundingBox())!.height).toBeGreaterThan(heightBefore);
  await handle.scrollIntoViewIfNeeded(); const shrink = await handle.boundingBox();
  await page.mouse.move(shrink!.x + shrink!.width / 2, shrink!.y + shrink!.height / 2); await page.mouse.down();
  await page.mouse.move(shrink!.x + shrink!.width / 2, shrink!.y + shrink!.height / 2 - 500, { steps: 8 }); await page.mouse.up();
  await expect.poll(async () => (await added.boundingBox())!.height).toBeLessThan(heightBefore);
  expect((await added.boundingBox())!.height).toBeGreaterThanOrEqual(260);
  expect(await added.locator('.studio-invoice-checks').evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true);
  await page.getByRole('button', { name: 'Finish editing layout' }).click();
  await page.getByRole('button', { name: 'Refresh local snapshot' }).click();
  await expect(checks).toHaveCount(2);
  await page.reload(); await expect(checks).toHaveCount(1, { timeout: 30000 });
  await page.setViewportSize({ width: 320, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await checks.getByRole('link').focus(); await expect(checks.getByRole('link')).toBeFocused();
  await page.emulateMedia({ forcedColors: 'active' }); await expect(checks.getByRole('heading', { name: 'Status needs review' })).toBeVisible();
});
