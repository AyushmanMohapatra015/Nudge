import { test, expect } from '@playwright/test';

test('manual brief review preserves draft status, resets confirmations and hides source notes from clients', async ({ page, request }) => {
  await request.post('/api/workspace', { data: { type: 'reset' } });
  await page.goto('/');
  await page.getByRole('button', { name: 'My project', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Brief review' });
  await panel.getByText('Start a brief review', { exact: true }).click();
  const notes = 'Private fictional brief: two marketing pages, no booking. Agreed USD 300.05.';
  await panel.getByLabel('Original brief notes').fill(notes);
  await panel.getByRole('button', { name: 'Start manual review' }).click();
  await expect(panel.getByLabel('Reviewed project name')).toBeVisible();
  await expect(panel.getByLabel('Reviewed client email')).toHaveValue('');
  const apply = panel.getByRole('button', { name: 'Use reviewed draft' });
  await expect(apply).toBeDisabled();
  await panel.getByLabel('Reviewed project name').fill('Fictional marketing website');
  await panel.getByLabel('Reviewed client name').fill('Fictional Studio');
  await panel.getByLabel('Reviewed client email').fill('buyer@example.com');
  await panel.getByLabel('Reviewed total price (USD)').fill('300.005');
  await panel.getByLabel('Reviewed scope clauses').fill('Two marketing pages are included.\nBooking systems are excluded.');
  await panel.getByLabel('Brief review note').fill('Checked the fictional brief and confirmed the scope and USD amount.');
  await panel.getByRole('checkbox').nth(0).check();
  await panel.getByRole('checkbox').nth(1).check();
  await expect(apply).toBeDisabled();
  await panel.getByLabel('Reviewed total price (USD)').fill('300.05');
  await expect(panel.getByRole('checkbox').nth(0)).not.toBeChecked();
  await expect(panel.getByRole('checkbox').nth(1)).not.toBeChecked();
  await panel.getByRole('checkbox').nth(0).check();
  await panel.getByRole('checkbox').nth(1).check();
  await expect(apply).toBeEnabled();
  await apply.click();
  await expect(panel.getByRole('heading', { name: 'Reviewed brief saved' })).toBeVisible();
  const workspace = await (await request.get('/api/workspace')).json();
  expect(workspace.agreementStatus).toBe('draft');
  expect(workspace.agreement.amountCents).toBe(30005);
  expect(workspace.invoices).toHaveLength(0);
  const client = await (await request.get(`/api/client/${workspace.clientToken}`)).json();
  expect(JSON.stringify(client)).not.toContain(notes);
  await page.reload();
  await page.getByRole('button', { name: 'My project', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Reviewed brief saved' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
