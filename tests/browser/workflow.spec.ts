import { test, expect } from '@playwright/test';
test('client acceptance gates changes and invoicing; reminders obey current policy and payment state', async ({ page, request, context }) => {
  await request.post('/api/workspace', { data: { type: 'reset' } });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Good work deserves to get paid.' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Compare with agreement' })).toBeDisabled();
  let response = await request.post('/api/workspace', { data: { type: 'createInvoice', id: 'base' } });
  expect(response.status()).toBe(400);
  await page.getByRole('button', { name: 'Approve scope' }).click();
  await expect(page.getByText('Waiting for client acceptance', { exact: true })).toBeVisible();
  let data = await (await request.get('/api/workspace')).json();
  const client = await context.newPage(); await client.goto(`/client/${data.clientToken}`);
  await expect(client.getByRole('button', { name: 'Accept project scope' })).toBeDisabled();
  await client.getByRole('checkbox').check(); await client.getByRole('button', { name: 'Accept project scope' }).click();
  await expect(client.getByText(/Scope accepted/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Compare with agreement' })).toBeEnabled({ timeout: 10000 });
  await page.getByRole('button', { name: 'Compare with agreement' }).click();
  await expect(page.getByText('Outside agreed scope')).toBeVisible();
  await page.getByPlaceholder('e.g. 300.00').fill('300.00');
  await page.getByRole('button', { name: 'Approve proposal' }).click();
  data = await (await request.get('/api/workspace')).json();
  response = await request.post('/api/workspace', { data: { type: 'createInvoice', id: data.proposals[0].id } }); expect(response.status()).toBe(400);
  await expect(client.getByRole('button', { name: 'Accept work & price' })).toBeVisible({ timeout: 10000 });
  await client.getByRole('button', { name: 'Accept work & price' }).click();
  await expect(page.getByRole('button', { name: 'Create PayPal invoice' })).toBeVisible({ timeout: 10000 });
  await page.getByRole('button', { name: 'Create PayPal invoice' }).click();
  await page.getByRole('button', { name: 'Payments', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Approve & send invoice' })).toBeVisible();
  await page.getByRole('button', { name: 'Approve & send invoice' }).click();
  await expect(page.getByRole('button', { name: 'Simulate payment' })).toBeVisible();
  await page.getByRole('button', { name: 'Simulate payment' }).click();
  await expect(page.getByText('$0.00', { exact: true }).first()).toBeVisible();
  data = await (await request.get('/api/workspace')).json(); expect(data.invoices[0].status).toBe('PAID'); expect(data.invoices[0].amountCents).toBe(30000);
  response = await request.post('/api/workspace', { data: { type: 'draftReminder', id: data.invoices[0].id } }); expect(response.status()).toBe(400);
  response = await request.post('/api/workspace', { data: { type: 'createInvoice', id: data.proposals[0].id } }); expect(response.status()).toBe(400);
  await request.post('/api/workspace', { data: { type: 'seedOverdue' } });
  await request.post('/api/workspace', { data: { type: 'draftReminder', id: 'SIM-OVERDUE' } });
  data = await (await request.get('/api/workspace')).json(); const draft = data.reminderDraft;
  await request.post('/api/workspace', { data: { type: 'policies', protectedClient: true, reminderLimit: 3, cooldownDays: 7 } });
  response = await request.post('/api/workspace', { data: { type: 'sendReminder', id: draft.id, note: draft.note } }); expect(response.status()).toBe(400);
  await request.post('/api/workspace', { data: { type: 'policies', protectedClient: false, reminderLimit: 3, cooldownDays: 7 } });
  await request.post('/api/workspace', { data: { type: 'simulatePayment', id: 'SIM-OVERDUE' } });
  response = await request.post('/api/workspace', { data: { type: 'sendReminder', id: draft.id, note: draft.note } }); expect(response.status()).toBe(400);
  response = await request.post('/api/workspace', { data: { type: 'dismissReminder', id: draft.id } }); expect(response.ok()).toBe(true);
  await expect(client.getByText('Thank you. This invoice is settled.')).toBeVisible({ timeout: 10000 });
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/workspace-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await expect(page.getByRole('heading', { name: 'Good work deserves to get paid.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/workspace-mobile.png', fullPage: true });
  await client.close();
});
test('invalid private links, cross-origin mutations, and fabricated webhook events are rejected', async ({ request }) => {
  expect((await request.get('/api/client/invalid')).status()).toBe(404);
  expect((await request.post('/api/workspace', { headers: { origin: 'https://untrusted.example' }, data: { type: 'reset' } })).status()).toBe(403);
  expect((await request.post('/api/paypal/webhook', { data: { id: 'forged', event_type: 'INVOICING.INVOICE.PAID', resource: { id: 'SIM-OVERDUE' } } })).status()).toBe(400);
});
